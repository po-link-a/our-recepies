const recipes = JSON.parse(readFileSync(FILE, 'utf8'));
const problems = [];
let translated = 0;

for (const recipe of recipes) {
  if (recipe.language === 'RU') continue;

  const t = TRANSLATIONS[recipe.slug];
  if (!t) {
    problems.push(`no translation for ${recipe.slug} (${recipe.language})`);
    continue;
  }
  if (t.ingredients.length !== recipe.ingredients.length) {
    problems.push(`${recipe.slug}: ${t.ingredients.length} ingredients vs ${recipe.ingredients.length}`);
    continue;
  }
  if (t.directions.length !== recipe.directions.length) {
    problems.push(`${recipe.slug}: ${t.directions.length} steps vs ${recipe.directions.length}`);
    continue;
  }

  recipe.title = t.title;
  recipe.directions = t.directions;
  recipe.ingredients = recipe.ingredients.map((ing, i) => {
    const [name, note] = t.ingredients[i];
    const next = { ...ing, name };
    if (note) next.note = note;
    else delete next.note;
    return next;
  });
  recipe.translatedFrom = recipe.language;
  translated++;
}

if (problems.length) {
  console.error('Refusing to write:\n  ' + problems.join('\n  '));
  process.exit(1);
}

writeFileSync(FILE, JSON.stringify(recipes, null, 2) + '\n');
console.log(`translated ${translated} recipes`);
